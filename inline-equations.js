function renderInlineEquations(root){
 if(!root || typeof katex==='undefined')return;
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT,{acceptNode(n){return n.parentElement && !n.parentElement.closest('.formula,.katex,.inline-math,.inline-fraction,.practice-score,script,style,code,svg,sub,sup')?NodeFilter.FILTER_ACCEPT:NodeFilter.FILTER_REJECT}});
 const nodes=[];while(walker.nextNode())nodes.push(walker.currentNode);
 for(const node of nodes){const text=node.nodeValue;let pos=0,frag=document.createDocumentFragment(),changed=false;
  while(pos<text.length){let best=null;for(const [raw,latex] of inlineEquations){let at=text.indexOf(raw,pos);while(at>=0){const before=text[at-1]||'',after=text[at+raw.length]||'';if(!/[\p{L}\p{N}_]/u.test(before)&&!/[\p{L}\p{N}_]/u.test(after))break;at=text.indexOf(raw,at+1)}if(at>=0&&(!best||at<best.at||(at===best.at&&raw.length>best.raw.length)))best={at,raw,latex}}
   if(!best)break;let span=document.createElement('span');span.className='inline-math';try{katex.render(best.latex,span,{throwOnError:true,output:'htmlAndMathml'})}catch(error){console.error('Ошибка оформления формулы',error);frag.append(document.createTextNode(text.slice(pos,best.at+best.raw.length)));pos=best.at+best.raw.length;continue}frag.append(document.createTextNode(text.slice(pos,best.at)),span);pos=best.at+best.raw.length;changed=true;
  }
  if(changed){frag.append(document.createTextNode(text.slice(pos)));node.replaceWith(frag)}
 }
}
